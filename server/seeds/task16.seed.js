/* ── helpers ──────────────────────────────────────────────────── */
function parseGaps(text) {
  const words = text.trim().split(/\s+/);
  const gaps = [];
  for (let i = 0; i < words.length; i++) {
    if (words[i].endsWith(',')) gaps.push(i);
  }
  return gaps;
}

function insertSentence(source_text, rule_types, explanation_md, source) {
  const gaps = parseGaps(source_text.trim());
  const existing = db.prepare('SELECT id FROM task16_sentences WHERE source_text = ?').get(source_text.trim());
  if (existing) return existing.id;
  const { lastInsertRowid } = db.prepare(`
    INSERT INTO task16_sentences
      (source_text, base_text, comma_positions_json, rule_types_json, explanation_md, source)
    VALUES (?, ?, ?, ?, ?, ?)
  `).run(
    source_text.trim(),
    source_text.trim(),
    JSON.stringify(gaps),
    JSON.stringify(rule_types),
    explanation_md || null,
    source || null,
  );
  return lastInsertRowid;
}

function insertTask(sentences, source) {
  const { lastInsertRowid: taskId } = db.prepare(
    'INSERT INTO task16_tasks (source) VALUES (?)'
  ).run(source || null);
  const ins = db.prepare('INSERT INTO task16_task_sentences (task_id, sentence_id, position) VALUES (?, ?, ?)');
  sentences.forEach((sid, i) => ins.run(taskId, sid, i + 1));
  return taskId;
}

/* ── очистка старых данных ────────────────────────────────────── */
