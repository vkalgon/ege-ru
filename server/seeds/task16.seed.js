db.transaction(() => {
  const oldTasks = db.prepare("SELECT id FROM task16_tasks WHERE source = ?").all(SOURCE);
  if (oldTasks.length) {
    const ids = oldTasks.map(t => t.id);
    db.prepare(`DELETE FROM task16_task_sentences WHERE task_id IN (${ids.map(() => '?').join(',')})`).run(...ids);
    db.prepare(`DELETE FROM task16_tasks WHERE id IN (${ids.map(() => '?').join(',')})`).run(...ids);
  }
  const oldSents = db.prepare("SELECT id FROM task16_sentences WHERE source = ?").all(SOURCE);
  if (oldSents.length) {
    const sids = oldSents.map(s => s.id);
    db.prepare(`DELETE FROM task16_task_sentences WHERE sentence_id IN (${sids.map(() => '?').join(',')})`).run(...sids);
    db.prepare(`DELETE FROM task16_sentences WHERE id IN (${sids.map(() => '?').join(',')})`).run(...sids);
  }
})();

